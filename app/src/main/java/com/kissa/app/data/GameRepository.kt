package com.kissa.app.data

import android.content.Context
import android.graphics.BitmapFactory
import android.util.Base64
import androidx.compose.ui.graphics.ImageBitmap
import androidx.compose.ui.graphics.asImageBitmap
import com.kissa.app.game.Game
import com.kissa.app.game.GameParser
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.withContext
import kotlinx.serialization.json.*
import okhttp3.OkHttpClient
import okhttp3.Request
import java.io.File
import java.util.concurrent.TimeUnit

/** Per-line lip-sync envelope generated by voicegen (25 fps amplitude bytes). */
class VoiceEnv(val fps: Int, val secs: Float, val env: ByteArray) {
    fun at(t: Float): Float { if (env.isEmpty()) return 0f; val i = (t * fps).toInt().coerceIn(0, env.size - 1); return (env[i].toInt() and 0xFF) / 255f }
}

/** A playable game pack: the parsed game, where its files live (bundled asset dir or a downloaded folder) and its voice envelopes. */
class GameEntry(val game: Game, val assetDir: String?, val fileDir: File?, val env: Map<String, VoiceEnv>, val sizeBytes: Long, val voiceBytes: Long) {
    val id get() = game.id
    val downloaded get() = fileDir != null
}

/**
 * Catalog loader. V1: the launch games are bundled in assets/games/<id>/ (game.json, voice_env.json, audio files (.ogg), cover.webp),
 * so they play fully offline. When BuildConfig.CATALOG_URL is set (Phase 2 CDN), [refreshRemote] downloads catalog.json and
 * any new/updated game packs into filesDir/games/<id>/ — no app update needed; downloaded packs override bundled ones.
 */
class GameRepository(private val ctx: Context, private val catalogUrl: String) {
    private val _entries = MutableStateFlow<List<GameEntry>>(emptyList())
    val entries: StateFlow<List<GameEntry>> = _entries
    private val covers = HashMap<String, ImageBitmap?>()
    val downloadsDir = File(ctx.filesDir, "games")

    fun entry(id: String) = _entries.value.firstOrNull { it.id == id }

    suspend fun load() = withContext(Dispatchers.IO) {
        val list = LinkedHashMap<String, GameEntry>()
        ctx.assets.list("games")?.sorted()?.forEach { dir ->
            runCatching {
                val text = ctx.assets.open("games/$dir/game.json").bufferedReader().readText()
                val g = GameParser.parse(text)
                val env = runCatching { parseEnv(ctx.assets.open("games/$dir/voice_env.json").bufferedReader().readText()) }.getOrDefault(emptyMap())
                val audio = ctx.assets.list("games/$dir/audio")?.sumOf { f -> runCatching { ctx.assets.openFd("games/$dir/audio/$f").use { it.length } }.getOrDefault(0L) } ?: 0L
                list[g.id] = GameEntry(g, "games/$dir", null, env, text.length.toLong(), audio)
            }
        }
        downloadsDir.listFiles()?.forEach { d ->
            runCatching {
                val f = File(d, "game.json"); if (!f.exists()) return@runCatching
                val text = f.readText(); val g = GameParser.parse(text)
                val env = File(d, "voice_env.json").takeIf { it.exists() }?.let { parseEnv(it.readText()) } ?: emptyMap()
                val audio = File(d, "audio").listFiles()?.sumOf { it.length() } ?: 0L
                list[g.id] = GameEntry(g, null, d, env, text.length.toLong(), audio)
            }
        }
        _entries.value = list.values.toList()
    }

    private fun parseEnv(text: String): Map<String, VoiceEnv> = Json.parseToJsonElement(text).jsonObject.mapValues { (_, v) ->
        val o = v.jsonObject
        VoiceEnv(o["fps"]!!.jsonPrimitive.int, o["secs"]?.jsonPrimitive?.float ?: 0f, Base64.decode(o["env"]!!.jsonPrimitive.content, Base64.DEFAULT))
    }

    /** Opens a pack-relative file (audio/…, cover.webp) as a file descriptor source for MediaPlayer, or null if missing. */
    fun audioExists(e: GameEntry, rel: String): Boolean = when {
        e.fileDir != null -> File(e.fileDir, rel).exists()
        e.assetDir != null -> runCatching { ctx.assets.openFd("${e.assetDir}/$rel").close(); true }.getOrDefault(false)
        else -> false
    }
    fun assetFd(e: GameEntry, rel: String) = e.assetDir?.let { runCatching { ctx.assets.openFd("$it/$rel") }.getOrNull() }
    fun file(e: GameEntry, rel: String) = e.fileDir?.let { File(it, rel) }?.takeIf { it.exists() }

    fun cover(e: GameEntry): ImageBitmap? = synchronized(covers) {
        covers.getOrPut(e.id) {
            val rel = e.game.cover ?: "cover.webp"
            runCatching {
                (file(e, rel)?.inputStream() ?: ctx.assets.open("${e.assetDir}/$rel")).use { BitmapFactory.decodeStream(it)?.asImageBitmap() }
            }.getOrNull()
        }
    }

    /** Phase 2 hook: fetch the CDN catalog and download changed packs. No-op while CATALOG_URL is empty (V1 ships bundled games). */
    suspend fun refreshRemote(): Result<Int> = withContext(Dispatchers.IO) {
        if (catalogUrl.isBlank()) return@withContext Result.success(0)
        runCatching {
            val http = OkHttpClient.Builder().connectTimeout(10, TimeUnit.SECONDS).readTimeout(30, TimeUnit.SECONDS).build()
            fun get(url: String): ByteArray = http.newCall(Request.Builder().url(url).build()).execute().use { r -> if (!r.isSuccessful) error("HTTP ${r.code} for $url"); r.body!!.bytes() }
            val cat = Json.parseToJsonElement(String(get(catalogUrl))).jsonObject
            var n = 0
            for (g in cat["games"]?.jsonArray ?: JsonArray(emptyList())) {
                val o = g.jsonObject; val id = o["id"]!!.jsonPrimitive.content; val base = o["base_url"]!!.jsonPrimitive.content.trimEnd('/')
                val version = o["version"]?.jsonPrimitive?.content ?: "1"
                val dir = File(downloadsDir, id); val ver = File(dir, ".version")
                if (ver.exists() && ver.readText() == version) continue
                val tmp = File(downloadsDir, "$id.tmp").apply { deleteRecursively(); mkdirs() }
                val gameBytes = get("$base/game.json"); File(tmp, "game.json").writeBytes(gameBytes)
                runCatching { File(tmp, "voice_env.json").writeBytes(get("$base/voice_env.json")) }
                runCatching { File(tmp, "cover.webp").writeBytes(get("$base/cover.webp")) }
                val game = GameParser.parse(String(gameBytes))
                val files = HashSet<String>()
                fun walk(e: JsonElement) { when (e) { is JsonObject -> e.forEach { (k, v) -> if (k == "voice_file") (v as? JsonPrimitive)?.contentOrNull?.let(files::add) else walk(v) }; is JsonArray -> e.forEach(::walk); else -> {} } }
                walk(game.raw)
                File(tmp, "audio").mkdirs()
                files.forEach { rel -> runCatching { File(tmp, rel).writeBytes(get("$base/$rel")) } }
                File(tmp, ".version").writeText(version)
                dir.deleteRecursively(); tmp.renameTo(dir); n++
            }
            load(); n
        }
    }

    /** Settings → Clear cache: removes downloaded packs (bundled launch games stay playable). */
    fun clearDownloads(): Long {
        val size = downloadsDir.walkTopDown().filter { it.isFile }.sumOf { it.length() }
        downloadsDir.deleteRecursively(); return size
    }
}
